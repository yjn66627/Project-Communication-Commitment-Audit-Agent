export const EGRESS_DENY_CODES = [
  "PRIVACY_REVISION_NOT_CONFIRMED",
  "PRIVACY_REVISION_MISMATCH",
  "REPORT_REFERENCE_INVALID",
  "SOURCE_REFERENCE_INVALID",
  "EGRESS_RAW_FIELD_DETECTED",
  "EGRESS_MAPPING_DETECTED",
  "EGRESS_SECRET_DETECTED",
  "EGRESS_PAYLOAD_NOT_ALLOWLISTED",
  "EGRESS_INTERNAL_FAILURE",
] as const;

export type EgressDenyCode = (typeof EGRESS_DENY_CODES)[number];
export type EgressSafeCategory = "PRIVACY" | "REFERENCE" | "PAYLOAD" | "SECRET" | "INTERNAL";

const CATEGORY_BY_CODE: Readonly<Record<EgressDenyCode, EgressSafeCategory>> = Object.freeze({
  PRIVACY_REVISION_NOT_CONFIRMED: "PRIVACY",
  PRIVACY_REVISION_MISMATCH: "PRIVACY",
  REPORT_REFERENCE_INVALID: "REFERENCE",
  SOURCE_REFERENCE_INVALID: "REFERENCE",
  EGRESS_RAW_FIELD_DETECTED: "PAYLOAD",
  EGRESS_MAPPING_DETECTED: "PAYLOAD",
  EGRESS_SECRET_DETECTED: "SECRET",
  EGRESS_PAYLOAD_NOT_ALLOWLISTED: "PAYLOAD",
  EGRESS_INTERNAL_FAILURE: "INTERNAL",
});

export function safeCategoryForEgressCode(code: EgressDenyCode): EgressSafeCategory {
  return CATEGORY_BY_CODE[code];
}
